"""llm_swarm.py — Real LLM Swarm and Scripted Fallback Runner (Task B7).

Features:
1. Dual-mode execution: 'llm' (Groq LLM-driven agent tool calling) vs 'scripted' (deterministic).
2. Explicit mode labeling: 'mode' is strictly 'llm' or 'scripted'.
3. Honest fallback: When GROQ_API_KEY is not set or Groq fails, result explicitly reports
   'LLM unavailable, fell back to scripted' instead of silently pretending.
4. Untrusted LLM output validation: Every tool call is schema-validated before dispatch.
5. All tool calls execute strictly through the Agent Gateway (/v1/call via GatewayClient).
   Policy, budgets, deduplication, admission, and coordination are enforced outside the LLM.
6. Real token usage and costs from API usage fields.
"""

