ALLOWED_TOOLS = {"read", "write", "guarded_write", "refund", "delete", "status"}


class ValidatedToolCall(BaseModel):
    """Schema validation for untrusted tool calls generated by an LLM."""

    tool: str
    payload: dict[str, Any] = Field(default_factory=dict)
    agent_id: str = Field(default="agent-llm")
    parent_call_id: str | None = None
    thought: str = Field(default="")

    @field_validator("tool")
    @classmethod
    def validate_tool_name(cls, v: str) -> str:
        clean = v.strip().lower()
        if clean not in ALLOWED_TOOLS:
            raise ValueError(f"Tool '{v}' is not allowed. Permitted: {sorted(ALLOWED_TOOLS)}")
        return clean

    @field_validator("payload")
    @classmethod
    def sanitize_payload(cls, v: dict[str, Any]) -> dict[str, Any]:
        if not isinstance(v, dict):
            raise ValueError("Payload must be a dictionary")
        return v


class LLMRunResult(BaseModel):
    """Structured result of an agent swarm execution."""

    goal_id: str
    mode: Literal["llm", "scripted"]
    llm_status: str
    fallback_reason: str | None = None
    duration_ms: float
    tokens: dict[str, Any]
    calls_made: int
    calls_avoided: int
    denials: int
    successful_calls: int
    traces: list[dict[str, Any]]
    schema_errors: list[str] = Field(default_factory=list)


SYSTEM_PROMPT = """You are an autonomous operations coordinator. Given the user's operational goal,
you must decide which tools to invoke to accomplish the mission.
Available tools:
- read: {"record": "string"} -> Read current record value.
- write: {"record": "string", "delta": integer} -> Increment record value (may overwrite if unguarded).
- guarded_write: {"record": "string", "delta": integer, "fencing_token": integer} -> Fenced safe write.
- refund: {"amount": float, "customer_id": "string"} -> Process refund (amounts >= 100 require manager approval).
- delete: {"record": "string"} -> Delete record (denied for read-only agents).

Output strictly a JSON object with:
"thought": "concise reasoning",
"tool_calls": [
  {"tool": "read", "agent_id": "reader-01", "payload": {"record": "order-hot-901"}},
  {"tool": "read", "agent_id": "reader-02", "payload": {"record": "order-hot-901"}},
  {"tool": "refund", "agent_id": "support-01", "payload": {"amount": 250, "customer_id": "vip-42"}}
]"""


class LLMSwarmRunner:
    """Executes agent swarms with dual LLM/scripted modes and gateway enforcement."""

    def __init__(self, sdk: GatewayClient, groq_engine: GroqSwarmEngine | None = None) -> None:
        self.sdk = sdk
        self.groq_engine = groq_engine or GroqSwarmEngine()

    async def run_goal(
        self,
        goal_id: str,
        prompt: str,
        *,
        mode: str = "auto",  # 'auto', 'llm', or 'scripted'
        scripted_calls_count: int = 10,
        seed: int = 42,
    ) -> LLMRunResult:
        """Run an agent swarm for a given goal either via live LLM or scripted fallback."""
        started = time.perf_counter()

        # Step 1: Initialize Goal in Gateway
        await self.sdk.create_goal(
            goal_id=goal_id,
            max_calls=150,
            max_depth=4,
            max_cost=1000.0,
            ttl_s=120.0,
        )

        chosen_mode: Literal["llm", "scripted"] = "scripted"
        llm_status: str = "scripted mode (deterministic)"
        fallback_reason: str | None = None
        usage = LLMUsage(source="none")
        raw_tool_calls: list[dict[str, Any]] = []

        # Determine mode
        wants_llm = mode in ("auto", "llm")
        if wants_llm:
            if not self.groq_engine.config.configured:
                chosen_mode = "scripted"
                llm_status = "LLM unavailable, fell back to scripted"
                fallback_reason = "GROQ_API_KEY environment variable not set"
            else:
                fallback_calls = [
                    {"tool": "read", "agent_id": "agent-001", "payload": {"record": "order-hot-901"}},
                    {"tool": "read", "agent_id": "agent-002", "payload": {"record": "order-hot-901"}},
                    {"tool": "refund", "agent_id": "support-01", "payload": {"amount": 250}},
                ]
                calls, token_usage, lat_ms, is_live, model, status_desc = await self.groq_engine.chat_tool_calls(
                    system_prompt=SYSTEM_PROMPT,
                    user_prompt=f"Goal: {prompt}\nSeed: {seed}",
                    fallback_tool_calls=fallback_calls,
                )
                if is_live:
                    chosen_mode = "llm"
                    llm_status = status_desc
                    usage = token_usage
                    raw_tool_calls = calls
                else:
                    chosen_mode = "scripted"
                    llm_status = "LLM unavailable, fell back to scripted"
                    fallback_reason = status_desc

        if chosen_mode == "scripted" and not raw_tool_calls:
            # Generate deterministic scripted calls
            workload = build_workload(count=scripted_calls_count, seed=seed)
            raw_tool_calls = [
                {"tool": c.tool, "agent_id": c.agent_id, "payload": c.payload}
                for c in workload
            ]

        # Step 2: Schema validation of untrusted LLM tool calls
        validated_calls: list[ValidatedToolCall] = []
        schema_errors: list[str] = []

        for idx, raw in enumerate(raw_tool_calls):
            try:
                val = ValidatedToolCall.model_validate(raw)
                validated_calls.append(val)
            except ValidationError as ve:
                err_msg = f"Call #{idx} schema error: {ve.errors()[0]['msg']}"
                schema_errors.append(err_msg)

        # Step 3: Execute all validated tool calls through Agent Gateway ONLY
        traces: list[dict[str, Any]] = []
        calls_made = 0
        successful = 0
        denials = 0

        async def execute_tool(vcall: ValidatedToolCall) -> None:
            nonlocal calls_made, successful, denials
            t0 = time.perf_counter()
            resp = await self.sdk.call(
                goal_id=goal_id,
                agent_id=vcall.agent_id,
                tool=vcall.tool,
                payload=vcall.payload,
                parent_call_id=vcall.parent_call_id,
            )
            lat = round((time.perf_counter() - t0) * 1000, 2)
            calls_made += 1
            if resp.status == "ok":
                successful += 1
            elif resp.status in ("denied", "budget_exceeded", "pending_approval", "throttled"):
                denials += 1

            traces.append({
                "agent_id": vcall.agent_id,
                "tool": vcall.tool,
                "payload": vcall.payload,
                "status": resp.status,
                "reason": resp.reason,
                "call_id": resp.call_id,
                "approval_id": resp.approval_id,
                "duration_ms": lat,
                "thought": vcall.thought,
            })

        # Run tool calls concurrently
        if validated_calls:
            await asyncio.gather(*(execute_tool(vc) for vc in validated_calls))

        # Fetch traces from gateway to determine avoided calls (via Singleflight dedup)
        try:
            goal_traces = await self.sdk.get_traces(goal_id)
            # Avoided calls = total client requests - requests forwarded
            # or from singleflight metrics
        except Exception:
            pass

        # Estimate avoided duplicate calls in this batch
        seen_keys: set[str] = set()
        calls_avoided = 0
        for vc in validated_calls:
            if vc.tool in ("read", "get", "status"):
                k = f"{vc.tool}:{sorted(vc.payload.items())}"
                if k in seen_keys:
                    calls_avoided += 1
                seen_keys.add(k)

        duration_ms = round((time.perf_counter() - started) * 1000, 1)

        return LLMRunResult(
            goal_id=goal_id,
            mode=chosen_mode,
            llm_status=llm_status,
            fallback_reason=fallback_reason,
            duration_ms=duration_ms,
            tokens=usage.to_dict(),
            calls_made=calls_made,
            calls_avoided=calls_avoided,
            denials=denials,
            successful_calls=successful,
            traces=traces,
            schema_errors=schema_errors,
        )
